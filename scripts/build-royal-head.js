const fs = require('fs');
const path = require('path');
const { marchingCubes } = require('isosurface');
const { deflateSync } = require('fflate');
const clamp = (n,a,b) => Math.max(a,Math.min(b,n));
const smooth = (a,b,x) => { const t=clamp((x-a)/(b-a),0,1);return t*t*(3-2*t); };
const mix = (a,b,t) => a.map((n,i)=>n+(b[i]-n)*t);
const linear = hex => [(hex>>16)&255,(hex>>8)&255,hex&255].map(n=>{n/=255;return n<=.04045?n/12.92:Math.pow((n+.055)/1.055,2.4);});

function ellipsoid(x,y,z,c,r) {
  const p=[x-c[0],y-c[1],z-c[2]];
  const a=Math.hypot(p[0]/r[0],p[1]/r[1],p[2]/r[2]);
  const b=Math.hypot(p[0]/(r[0]*r[0]),p[1]/(r[1]*r[1]),p[2]/(r[2]*r[2]));
  return b?a*(a-1)/b:-Math.min(...r);
}
function union(a,b,k) { const h=clamp(.5+.5*(b-a)/k,0,1);return b+(a-b)*h-k*h*(1-h); }
function outer(x,y,z) {
  let d=ellipsoid(x,y,z,[0,1.40,0],[.755,.51,.435]);
  d=union(d,ellipsoid(x,y,z,[0,1.05,.045],[.64,.29,.405]),.15);
  for(const side of[-1,1]){
    d=union(d,ellipsoid(x,y,z,[side*.55,1.15,.075],[.28,.30,.36]),.13);
    d=union(d,ellipsoid(x,y,z,[side*.47,1.69,.045],[.33,.37,.35]),.12);
  }
  return d;
}
function mouth(x,y,z) {
  const bowl=ellipsoid(x,y,z,[0,1.25,.465],[.29,.32,.29]);
  const lip=y-(1.25+.08*Math.pow(x/.29,2));
  return Math.max(bowl,lip);
}
function potential(x,y,z) {
  let d=outer(x,y,z);
  for(const side of[-1,1]){
    d=Math.max(d,-ellipsoid(x,y,z,[side*.47,1.685,.33],[.265,.292,.255]));
    d=Math.max(d,-ellipsoid(x,y,z,[side*.085,1.405,.426],[.027,.019,.036]));
  }
  return Math.max(d,-mouth(x,y,z));
}

const result=marchingCubes([82,66,58],potential,[[-1.02,.72,-.57],[1.02,2.15,.69]]);
const vertices=[],lookup=new Map(),faces=[];
result.cells.forEach(cell=>{
  const face=cell.map(index=>{
    const p=result.positions[index],key=p.map(n=>Math.round(n*100000)).join(',');
    if(!lookup.has(key)){lookup.set(key,vertices.length);vertices.push(p);}
    return lookup.get(key);
  });
  if(new Set(face).size===3)faces.push(face);
});
const gradient=p=>{
  const h=.0008,[x,y,z]=p;
  const g=[potential(x+h,y,z)-potential(x-h,y,z),potential(x,y+h,z)-potential(x,y-h,z),potential(x,y,z+h)-potential(x,y,z-h)];
  const length=Math.hypot(...g)||1;return g.map(n=>n/length);
};
const normals=vertices.map(gradient),skinFaces=[],mouthFaces=[];
faces.forEach(face=>{
  const [a,b,c]=face.map(i=>vertices[i]);
  const u=b.map((n,i)=>n-a[i]),v=c.map((n,i)=>n-a[i]);
  const cross=[u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]];
  const normal=normals[face[0]];
  if(cross.reduce((sum,n,i)=>sum+n*normal[i],0)<0)face=[face[0],face[2],face[1]];
  const center=a.map((n,i)=>(n+b[i]+c[i])/3);
  const isMouth=-mouth(...center)>outer(...center)+.001&&center[1]<1.37&&Math.abs(center[0])<.34;
  (isMouth?mouthFaces:skinFaces).push(...face);
});

const green=linear(0x94c631),cream=linear(0xf2d5a6),pink=linear(0xed8291),spot=linear(0x669530);
const colors=vertices.flatMap(([x,y,z])=>{
  let color=mix(green,cream,(1-smooth(1.10,1.32,y))*smooth(-.05,.20,z));
  const cheek=Math.exp(-Math.pow((Math.abs(x)-.575)/.17,2)-Math.pow((y-1.18)/.145,2)-Math.pow((z-.345)/.30,2))*.98;
  color=mix(color,pink,cheek);
  const marks=[[-.14,1.73,.32,.048],[.02,1.78,.285,.055],[.17,1.72,.32,.046],[.02,1.65,.37,.052],
    [-.75,1.40,.17,.049],[-.74,1.28,.27,.043],[-.68,1.23,.35,.045],[.75,1.40,.17,.046],[.74,1.28,.27,.05]];
  for(const [a,b,c,r]of marks){const d=Math.hypot((x-a)/r,(y-b)/(r*.8),(z-c)/(r*1.35));color=mix(color,spot,1-smooth(.5,1.25,d));}
  return color.map(n=>Math.round(clamp(n,0,1)*255));
});
const positions=new Int16Array(vertices.flatMap(p=>p.map(n=>Math.round(n*10000))));
const normalData=new Int8Array(normals.flatMap(p=>p.map(n=>Math.round(n*127))));
const indices=new Uint16Array([...skinFaces,...mouthFaces]);
if(vertices.length>65535)throw Error('Royal head exceeds 16-bit mesh budget');
const base64=array=>Buffer.from(deflateSync(new Uint8Array(array.buffer,array.byteOffset,array.byteLength),{level:9})).toString('base64');
function front(x,y) {
  let lo=0,hi=.75;
  for(let i=0;i<24;i++){const mid=(lo+hi)/2;if(outer(x,y,mid)<0)lo=mid;else hi=mid;}
  return (lo+hi)/2;
}
const lip=[];
for(let i=0;i<96;i++){
  const a=i/96*Math.PI*2;let lo=0,hi=1.5;
  for(let j=0;j<24;j++){
    const t=(lo+hi)/2,x=Math.cos(a)*.32*t,y=1.12+Math.sin(a)*.28*t;
    if(mouth(x,y,front(x,y))<0)lo=t;else hi=t;
  }
  const t=(lo+hi)/2,x=Math.cos(a)*.32*t,y=1.12+Math.sin(a)*.28*t;lip.push([x,y,front(x,y)+.002]);
}
const asset={version:2,compressed:true,scale:.0001,vertexCount:vertices.length,skinCount:skinFaces.length,mouthCount:mouthFaces.length,
  positions:base64(positions),normals:base64(normalData),colors:base64(new Uint8Array(colors)),indices:base64(indices),lip};
const file=path.join(__dirname,'../pages/index/models/royal-head.js');
fs.mkdirSync(path.dirname(file),{recursive:true});
fs.writeFileSync(file,'// Generated by scripts/build-royal-head.js.\nmodule.exports = '+JSON.stringify(asset)+';\n');
console.log('Royal head:',vertices.length,'vertices,',indices.length/3,'triangles,',fs.statSync(file).size,'bytes');
