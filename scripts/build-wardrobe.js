const fs=require('fs');
const path=require('path');
const {deflateSync}=require('fflate');
const {createScopedThreejs}=require('../miniprogram_npm/threejs-miniprogram');
const T=createScopedThreejs({createImage(){return{};},requestAnimationFrame(){return 1;},cancelAnimationFrame(){}});
const art=require('../pages/index/art')(T,{buildAssets:true}),mats=art.materials();
const frog=art.makeFrog({costume:'king',accent:0xf5c849},1,mats),assets={units:{},meshes:{},recipes:{}};
const pack=array=>Buffer.from(deflateSync(new Uint8Array(array.buffer,array.byteOffset,array.byteLength),{level:9})).toString('base64');
function encode(geometry){
  const attributes={};
  for(const [name,attribute] of Object.entries(geometry.attributes)){
    attributes[name]={type:'f32',scale:1,size:attribute.itemSize,data:pack(attribute.array)};
  }
  if(geometry.attributes.position.count>65535)throw Error('Wardrobe requires 16-bit indices');
  return {attributes,index:pack(geometry.index.array)};
}
assets.units.tuft=encode(new T.SphereBufferGeometry(1,10,8));
assets.units.small=encode(new T.SphereBufferGeometry(1,8,6));
frog.traverse(node=>{
  if(!node.name.startsWith('fur-'))return;
  const material=Object.keys(mats).find(key=>mats[key]===node.material);
  if(node.userData.recipe)assets.recipes[node.name]={material,parts:node.userData.recipe.map(part=>{
    const result={unit:part.unit};for(const key of ['p','r','s'])result[key]=part[key].map(n=>Math.round(n*1e7)/1e7);return result;
  })};
  else assets.meshes[node.name]=Object.assign(encode(node.geometry),{material});
});
const file=path.join(__dirname,'../pages/index/models/royal-fur.js');
fs.writeFileSync(file,'// Generated by scripts/build-wardrobe.js.\nmodule.exports = '+JSON.stringify(assets)+';\n');
console.log('Baked fur curves, primitive meshes and placement recipes: '+fs.statSync(file).size+' bytes');
